#!/usr/bin/env python3
"""Build directional pose CSR datasets from Three.js color-id samples.

Each JSONL sample is kept as one training pose.  The stored camera pose and
FOV are the model sampling/inference camera, currently 66 degrees.  Visible
weights come from screen coverage parts-per-million generated by the color-id
renderer.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import shutil
from pathlib import Path
from typing import Any

import numpy as np
from tqdm import tqdm


CATEGORY_IDS = {
    "street_gap": 0,
    "near_building": 1,
    "plaza": 2,
    "perimeter": 3,
    "sky": 4,
    "far": 5,
    "unknown": 255,
}
SPLIT_IDS = {"train": 0, "val": 1, "test": 2, "unknown": 255}
MODEL_INPUT_FOV_Y_DEG = 66.0
FRONTEND_RENDER_FOV_Y_DEG = 60.0
DIRECTIONAL_POSE_DTYPE = np.dtype(
    {
        "names": [
            "camera_norm",
            "camera_world",
            "camera_forward",
            "camera_view",
            "split",
            "category",
            "reserved0",
            "reserved1",
        ],
        "formats": [
            ("<f4", (3,)),
            ("<f4", (3,)),
            ("<f4", (3,)),
            ("<f4", (2,)),
            "u1",
            "u1",
            "<u2",
            "<u4",
        ],
        "offsets": [0, 12, 24, 36, 44, 45, 46, 48],
        "itemsize": 64,
    }
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build pose CSR from Three.js color-id JSONL samples.")
    parser.add_argument("--samples", type=Path, nargs="+", required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--runtime-meta", type=Path, required=True)
    parser.add_argument("--experiment", default="threejs_color_id_pose_csr_fov66_v1")
    parser.add_argument("--near", type=float, default=0.05)
    parser.add_argument("--train-ratio", type=float, default=0.80)
    parser.add_argument("--val-ratio", type=float, default=0.10)
    parser.add_argument("--seed", type=int, default=20260623)
    return parser.parse_args()


def read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def iter_jsonl(paths: list[Path]) -> list[dict[str, Any]]:
    files: list[Path] = []
    for path in paths:
        if path.is_dir():
            files.extend(sorted(path.glob("samples_fov66_h288_*.jsonl")))
        else:
            files.append(path)
    records: list[dict[str, Any]] = []
    for file in sorted(files):
        with file.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                records.append(json.loads(line))
    records.sort(key=lambda row: int(row.get("pose_index", 0)))
    return records


def scene_min_max(scene_bounds: dict[str, Any]) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    if "min" in scene_bounds and "max" in scene_bounds:
        mn = np.asarray(scene_bounds["min"], dtype=np.float32)
        mx = np.asarray(scene_bounds["max"], dtype=np.float32)
        return mn, mx, mx - mn
    center = np.asarray(scene_bounds["center"], dtype=np.float32)
    size = np.asarray(scene_bounds["size"], dtype=np.float32)
    return center - size * 0.5, center + size * 0.5, size


def bounds_min_max(bounds: dict[str, Any]) -> tuple[np.ndarray, np.ndarray]:
    if "min" in bounds and "max" in bounds:
        return np.asarray(bounds["min"], dtype=np.float32), np.asarray(bounds["max"], dtype=np.float32)
    center = np.asarray(bounds["center"], dtype=np.float32)
    size = np.asarray(bounds["size"], dtype=np.float32)
    return center - size * 0.5, center + size * 0.5


def load_world_aabbs(runtime_meta: dict[str, Any]) -> np.ndarray:
    records = runtime_meta.get("componentRecords", [])
    count = max(int(record["componentGlobalId"]) for record in records) + 1 if records else 0
    aabbs = np.zeros((count, 6), dtype=np.float32)
    for record in records:
        idx = int(record["componentGlobalId"])
        mn, mx = bounds_min_max(record["bounds"])
        aabbs[idx, :3] = mn
        aabbs[idx, 3:] = mx
    return aabbs


def normalize(v: np.ndarray, fallback: np.ndarray) -> np.ndarray:
    n = float(np.linalg.norm(v))
    if n < 1e-6:
        return fallback.astype(np.float32, copy=True)
    return (v / n).astype(np.float32, copy=False)


def camera_basis(forward: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    f = normalize(forward, np.asarray([0.0, 0.0, -1.0], dtype=np.float32))
    up_ref = np.asarray([0.0, 1.0, 0.0], dtype=np.float32)
    if abs(float(np.dot(f, up_ref))) > 0.98:
        up_ref = np.asarray([0.0, 0.0, 1.0], dtype=np.float32)
    right = normalize(np.cross(f, up_ref), np.asarray([1.0, 0.0, 0.0], dtype=np.float32))
    up = normalize(np.cross(right, f), np.asarray([0.0, 1.0, 0.0], dtype=np.float32))
    return f, right, up


def conservative_mvp(camera_world: np.ndarray, forward: np.ndarray, tan_x: float, tan_y: float) -> np.ndarray:
    f, right, up = camera_basis(forward)
    cam = camera_world.astype(np.float32, copy=False)
    tx = max(float(tan_x), 1e-4)
    ty = max(float(tan_y), 1e-4)
    e = np.zeros((16,), dtype=np.float32)
    e[0], e[4], e[8], e[12] = right[0] / tx, right[1] / tx, right[2] / tx, -float(np.dot(right, cam)) / tx
    e[1], e[5], e[9], e[13] = up[0] / ty, up[1] / ty, up[2] / ty, -float(np.dot(up, cam)) / ty
    e[2], e[6], e[10], e[14] = f[0], f[1], f[2], -float(np.dot(f, cam))
    e[3], e[7], e[11], e[15] = f[0], f[1], f[2], -float(np.dot(f, cam))
    return e


def frustum_candidate_ids(
    camera_world: np.ndarray,
    forward: np.ndarray,
    tan_x: float,
    tan_y: float,
    aabbs: np.ndarray,
    near: float,
) -> np.ndarray:
    if aabbs.size == 0:
        return np.zeros((0,), dtype=np.uint32)
    f, right, up = camera_basis(forward)
    mins = aabbs[:, :3]
    maxs = aabbs[:, 3:]
    centers = (mins + maxs) * 0.5
    extents = np.maximum((maxs - mins) * 0.5, 0.0)
    d = centers - camera_world.astype(np.float32, copy=False)[None, :]
    z = d @ f
    x = d @ right
    y = d @ up
    rz = extents @ np.abs(f)
    rx = extents @ np.abs(right)
    ry = extents @ np.abs(up)
    front = z + rz >= float(near)
    x_inside = (np.abs(x) - rx) <= ((z + rz) * max(float(tan_x), 1e-4))
    y_inside = (np.abs(y) - ry) <= ((z + rz) * max(float(tan_y), 1e-4))
    return np.flatnonzero(front & x_inside & y_inside).astype(np.uint32)


def normalize_points(points: np.ndarray, bounds: dict[str, Any]) -> np.ndarray:
    mn, _mx, size = scene_min_max(bounds)
    return np.clip((points - mn[None, :]) / np.maximum(size[None, :], 1e-6), 0.0, 1.0).astype(np.float32, copy=False)


def assign_splits(count: int, train_ratio: float, val_ratio: float, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    order = rng.permutation(count)
    split = np.full((count,), SPLIT_IDS["test"], dtype=np.uint8)
    train_end = int(round(count * float(train_ratio)))
    val_end = int(round(count * (float(train_ratio) + float(val_ratio))))
    split[order[:train_end]] = SPLIT_IDS["train"]
    split[order[train_end:val_end]] = SPLIT_IDS["val"]
    return split


def main() -> None:
    args = parse_args()
    output_dir = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)
    runtime_meta = read_json(args.runtime_meta)
    records = iter_jsonl(args.samples)
    if not records:
        raise RuntimeError("No color-id JSONL samples were found.")
    pose_indices = [int(row.get("pose_index", i)) for i, row in enumerate(records)]
    if len(set(pose_indices)) != len(pose_indices):
        raise RuntimeError("Duplicate pose_index values in color-id samples.")

    aabbs = load_world_aabbs(runtime_meta)
    camera_world = np.asarray([row.get("camera_pos", [0, 0, 0]) for row in records], dtype=np.float32)
    camera_forward = np.asarray(
        [normalize(np.asarray(row.get("camera_forward", [0, 0, -1]), dtype=np.float32), np.asarray([0, 0, -1], dtype=np.float32)) for row in records],
        dtype=np.float32,
    )
    fov_y = np.asarray([float(row.get("fov_y", MODEL_INPUT_FOV_Y_DEG)) for row in records], dtype=np.float32)
    if not np.allclose(fov_y, MODEL_INPUT_FOV_Y_DEG, atol=1e-6):
        raise RuntimeError(
            f"Color-ID samples must use the model FOV of {MODEL_INPUT_FOV_Y_DEG} degrees."
        )
    aspect = np.asarray([float(row.get("aspect", 16.0 / 9.0)) for row in records], dtype=np.float32)
    tan_y = np.tan(np.deg2rad(fov_y) * 0.5).astype(np.float32)
    tan_x = (tan_y * aspect).astype(np.float32)

    scene_min, scene_max, _scene_size = scene_min_max(runtime_meta["sceneBounds"])
    cam_min = np.minimum(scene_min, camera_world.min(axis=0))
    cam_max = np.maximum(scene_max, camera_world.max(axis=0))
    pad = np.maximum((cam_max - cam_min) * 0.05, 1.0)
    camera_bounds = {
        "min": (cam_min - pad).astype(float).tolist(),
        "max": (cam_max + pad).astype(float).tolist(),
        "center": ((cam_min + cam_max) * 0.5).astype(float).tolist(),
        "size": ((cam_max - cam_min) + pad * 2.0).astype(float).tolist(),
    }
    camera_norm = normalize_points(camera_world, camera_bounds)
    split_ids = assign_splits(len(records), args.train_ratio, args.val_ratio, args.seed)

    poses = np.zeros((len(records),), dtype=DIRECTIONAL_POSE_DTYPE)
    poses["camera_norm"] = camera_norm
    poses["camera_world"] = camera_world
    poses["camera_forward"] = camera_forward
    poses["camera_view"] = np.stack([tan_x, tan_y], axis=1).astype(np.float32, copy=False)
    poses["split"] = split_ids
    poses["category"] = np.asarray(
        [int(row.get("sample_category_id", CATEGORY_IDS.get(str(row.get("sample_category", "unknown")), 255))) for row in records],
        dtype=np.uint8,
    )

    mvps = np.zeros((len(records), 16), dtype=np.float32)
    visible_offsets = np.zeros((len(records) + 1,), dtype=np.uint64)
    candidate_offsets = np.zeros((len(records) + 1,), dtype=np.uint64)
    visible_ids_all: list[int] = []
    visible_weights_all: list[float] = []
    stats = {
        "candidateMissVisible": 0,
        "visibleSubsetFailures": 0,
        "emptyCandidate": 0,
        "emptyVisible": 0,
        "totalCandidateRefs": 0,
        "maxCandidate": 0,
    }
    candidate_path = output_dir / "candidate_ids.bin"
    with candidate_path.open("wb") as candidate_file:
        for i, row in enumerate(tqdm(records, desc="color-id-pose-csr")):
            mvps[i] = conservative_mvp(camera_world[i], camera_forward[i], float(tan_x[i]), float(tan_y[i]))
            raw_ids = row.get("visible_component_ids") or []
            raw_weights = row.get("component_weights") or []
            weights_by_id: dict[int, float] = {}
            for j, cid_raw in enumerate(raw_ids):
                cid = int(cid_raw)
                if cid < 0 or cid >= aabbs.shape[0]:
                    raise ValueError(f"visible id {cid} is outside runtime component range at pose {i}")
                weight = float(raw_weights[j]) if j < len(raw_weights) else 1.0
                weights_by_id[cid] = max(weights_by_id.get(cid, 0.0), weight)
            visible = np.asarray(sorted(weights_by_id), dtype=np.uint32)
            if visible.size == 0:
                stats["emptyVisible"] += 1
            visible_ids_all.extend(int(v) for v in visible.tolist())
            visible_weights_all.extend(float(weights_by_id[int(v)]) for v in visible.tolist())
            visible_offsets[i + 1] = len(visible_ids_all)

            candidates = frustum_candidate_ids(camera_world[i], camera_forward[i], float(tan_x[i]), float(tan_y[i]), aabbs, args.near)
            candidate_set = set(int(v) for v in candidates.tolist())
            missing_visible = np.setdiff1d(visible, candidates, assume_unique=False)
            if missing_visible.size:
                stats["candidateMissVisible"] += int(missing_visible.size)
                raise RuntimeError(
                    "Color-ID visible instances fall outside the native back-camera "
                    f"AABB candidate set at pose {pose_indices[i]}: "
                    f"{missing_visible.size} missing IDs; first IDs="
                    f"{missing_visible[:16].tolist()}. Rebuild the sample with the "
                    "same FOV/near-plane and candidate convention instead of "
                    "augmenting candidates with GT-visible instances."
                )
            candidates = np.asarray(sorted(candidate_set), dtype=np.uint32)
            if candidates.size == 0:
                stats["emptyCandidate"] += 1
            if np.setdiff1d(visible, candidates, assume_unique=False).size:
                stats["visibleSubsetFailures"] += 1
            candidate_file.write(candidates.tobytes(order="C"))
            candidate_offsets[i + 1] = candidate_offsets[i] + int(candidates.size)
            stats["totalCandidateRefs"] += int(candidates.size)
            stats["maxCandidate"] = max(int(stats["maxCandidate"]), int(candidates.size))

    poses.tofile(output_dir / "poses.bin")
    mvps.tofile(output_dir / "mvp.bin")
    visible_offsets.tofile(output_dir / "visible_offsets.bin")
    np.asarray(visible_ids_all, dtype="<u4").tofile(output_dir / "visible_ids.bin")
    np.asarray(visible_weights_all, dtype="<f4").tofile(output_dir / "visible_weights.bin")
    candidate_offsets.tofile(output_dir / "candidate_offsets.bin")
    candidate_offsets.tofile(output_dir / "frustum_offsets.bin")
    try:
        frustum_path = output_dir / "frustum_ids.bin"
        if frustum_path.exists():
            frustum_path.unlink()
        os.link(candidate_path, frustum_path)
    except OSError:
        shutil.copyfile(candidate_path, output_dir / "frustum_ids.bin")

    category_counts = {
        name: int(np.count_nonzero(poses["category"] == cid))
        for name, cid in CATEGORY_IDS.items()
        if name != "unknown"
    }
    split_counts = {name: int(np.count_nonzero(split_ids == sid)) for name, sid in SPLIT_IDS.items() if name != "unknown"}
    meta = {
        "schema": "pose-csr-color-id-fov66-v1",
        "experiment": args.experiment,
        "runtimeMeta": str(args.runtime_meta.as_posix()),
        "poseCount": int(len(records)),
        "numInstances": int(aabbs.shape[0]),
        "poseStrideBytes": int(DIRECTIONAL_POSE_DTYPE.itemsize),
        "mvpStrideBytes": 64,
        "visibleCount": int(len(visible_ids_all)),
        "candidateCount": int(candidate_offsets[-1]),
        "candidateSemantics": "native AABB candidates under the sampled 66 degree model camera; visible IDs are checked as a subset and never added",
        "cameraSemantics": "camera_world/camera_forward/fov are copied from Three.js color-id sampling poses",
        "gtSemantics": "visible_ids are exact color-id rasterized visible componentGlobalId values for one sampled pose",
        "visibleWeightSemantics": "Three.js color-id screen coverage in parts per million",
        "visibleWeightDtype": "float32",
        "modelInputFovYDeg": MODEL_INPUT_FOV_Y_DEG,
        "frontendRenderFovYDeg": FRONTEND_RENDER_FOV_Y_DEG,
        "cameraBounds": camera_bounds,
        "splitIds": SPLIT_IDS,
        "categoryIds": CATEGORY_IDS,
        "categoryCounts": category_counts,
        "splitCounts": split_counts,
        "stats": {
            **stats,
            "avgCandidate": float(stats["totalCandidateRefs"] / max(1, len(records))),
            "avgVisible": float(len(visible_ids_all) / max(1, len(records))),
            "fovYRange": [float(np.min(fov_y)), float(np.max(fov_y))],
            "fovXRange": [float(np.rad2deg(np.arctan(tan_x).min() * 2.0)), float(np.rad2deg(np.arctan(tan_x).max() * 2.0))],
        },
        "sourceSamples": [str(path.as_posix()) for path in args.samples],
        "files": {
            "poses": "poses.bin",
            "mvp": "mvp.bin",
            "visibleOffsets": "visible_offsets.bin",
            "visibleIds": "visible_ids.bin",
            "visibleWeights": "visible_weights.bin",
            "candidateOffsets": "candidate_offsets.bin",
            "candidateIds": "candidate_ids.bin",
            "frustumOffsets": "frustum_offsets.bin",
            "frustumIds": "frustum_ids.bin",
        },
    }
    (output_dir / "dataset_meta.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(meta, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
